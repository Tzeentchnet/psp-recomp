/* The squarer only sees the top 10 bits of x2, as a distance from the middle of the segment. */
static int32_t vfpu_square(uint32_t x2) {
    int32_t t = abs((int32_t)(x2 >> 6) - 512);
    return (t * t + 255) >> 8;
}

static int32_t vfpu_interp(const VfpuSegment *seg, uint32_t x2) {
    return seg->c0 + (int32_t)(((int64_t)seg->m * x2) >> 17) + ((seg->n * vfpu_square(x2)) >> 9);
}

static int clz64_nonzero(uint64_t v) {
    return (v >> 32) != 0 ? __builtin_clz((uint32_t)(v >> 32)) : 32 + __builtin_clz((uint32_t)v);
}

/* Float bits of v * 2^-frac_bits, with the sign bit set if negative (also for zero). */
static uint32_t fixed_to_bits(uint64_t v, int frac_bits, int negative) {
    uint32_t sign = negative ? 0x80000000u : 0u;
    if (v == 0) return sign;
    int top = 63 - clz64_nonzero(v);
    uint64_t significand = top <= 23 ? v << (23 - top) : v >> (top - 23);
    return sign + ((uint32_t)(top - frac_bits + 127) << 23) + ((uint32_t)significand & 0x007FFFFFu);
}

static uint32_t asin_fixed(uint32_t x) {
    if (x == 0u) return 0u;
    if (x == 1u << 23) return 1u << 30;
    const VfpuSegment *seg = &s_asin_segments[x >> 16];
    /* The first segment is linear, and keeps the 2^-30 step of the fixed-point output. */
    uint32_t v = (uint32_t)vfpu_interp(seg, x & 0xFFFF) & ((x >> 16) == 0 ? ~1u : ~3u);
    return seg->e >= 120 ? v << (seg->e - 120) : v >> (120 - seg->e);
}

float sr_vfpu_asin(float x) {
    uint32_t bits, result;
    memcpy(&bits, &x, 4);
    uint32_t sign = bits & 0x80000000u, a = bits & 0x7FFFFFFFu;
    if (a > 0x3F800000u) {
        result = 0x7F800001u ^ sign;
    } else {
        /* |x| * 2^23, truncated. Anything below 2^-23, denormals included, gives 0. */
        int e = (int)(a >> 23);
        uint32_t significand = (a & 0x007FFFFFu) | 0x00800000u;
        uint32_t fixed = e < 104 ? 0 : significand >> (127 - e);
        result = fixed_to_bits(asin_fixed(fixed), 30, sign != 0);
    }
    memcpy(&x, &result, 4);
    return x;
}
